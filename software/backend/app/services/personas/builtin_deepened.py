DEEPENED_PERSONAS = {item.persona_id: item for item in (SHUHENG, HUAIXI, YOUTING)}


def find_deepened(persona_id: str | None, persona: dict | None = None) -> DeepenedPersona | None:
    data = persona if isinstance(persona, dict) else {}
    for key in (persona_id, data.get("builtinId"), data.get("builtin_id")):
        found = DEEPENED_PERSONAS.get(str(key or "").strip().lower())
        if found:
            return found
    return None


def fill_deepened_prompt(item: DeepenedPersona, char_name: str = "", user_name: str = "你") -> str:
    name = (char_name or item.char_name).strip() or item.char_name
    user = (user_name or "你").strip() or "你"
    text = f"# 萨福 · 固有人设 {item.char_name} System Prompt\n\n{item.body}\n\n{SHARED_RULES}"
    return text.replace("{{CHAR_NAME}}", name).replace("{{USER_NAME}}", user)
